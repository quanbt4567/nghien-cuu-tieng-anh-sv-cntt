export function normalizeChainWord(word: string): string {
  if (typeof word !== "string") return "";
  return word.trim().toLowerCase().replace(/^[^a-z]+|[^a-z]+$/g, "");
}

export function isItChainTerm(word: string): boolean {
  const normalized = normalizeChainWord(word);
  if (!normalized) return false;
  return IT_WORD_CHAIN_SET.has(normalized);
}

export function pickBotChainWord(
  requiredChar: string,
  usedWords: Iterable<string>
): string | null {
  const normalizedChar =
    typeof requiredChar === "string"
      ? requiredChar.trim().toLowerCase().replace(/[^a-z]/g, "").slice(0, 1)
      : "";
  if (!normalizedChar) return null;

  const usedSet = new Set<string>();
  for (const w of Array.from(usedWords)) {
    const norm = normalizeChainWord(w);
    if (norm) usedSet.add(norm);
  }

  const candidates = IT_WORD_CHAIN_TERMS.filter(
    (term) => term.startsWith(normalizedChar) && !usedSet.has(term)
  );
  if (candidates.length === 0) return null;

  const nonDeadEnd = candidates.filter((candidate) => {
    const tail = candidate[candidate.length - 1];
    return IT_WORD_CHAIN_TERMS.some(
      (next) => next !== candidate && !usedSet.has(next) && next.startsWith(tail)
    );
  });

  const pool = nonDeadEnd.length > 0 ? nonDeadEnd : candidates;
  const idx = (usedSet.size * 7 + normalizedChar.charCodeAt(0)) % pool.length;
  return pool[idx];
}

